import { existsSync, readFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { join } from 'node:path';
import { repoSlug } from './git.mjs';

function git(dir, args) {
  try {
    return execFileSync('git', ['-C', dir, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
  } catch { return ''; }
}

function readJson(p) {
  try { return JSON.parse(readFileSync(p, 'utf8')); } catch { return null; }
}

/** Detect facts about a repository checkout. Pure inspection, no side effects. */
export function detectRepo(dir) {
  const pkg = readJson(join(dir, 'package.json')) || {};
  const deps = { ...pkg.dependencies, ...pkg.devDependencies };
  const has = (f) => existsSync(join(dir, f));
  const scripts = pkg.scripts || {};
  const eds = has('fstab.yaml') || has('head.html') || has('scripts/aem.js') || has('scripts/lib-franklin.js');
  const worker = has('wrangler.toml') || has('wrangler.jsonc') || has('wrangler.json');
  const helixService = Boolean(deps['@adobe/helix-deploy'] || deps['helix-deploy']);
  const testFw = ['vitest', 'jest', 'mocha', '@web/test-runner', 'playwright', '@playwright/test', 'ava']
    .filter((d) => deps[d]);
  const usesEsmock = Boolean(deps.esmock);
  const defaultBranch = (git(dir, ['symbolic-ref', '--short', 'refs/remotes/origin/HEAD']) || 'origin/main').replace(/^origin\//, '');
  let server = scripts.dev ? 'npm run dev' : scripts.start ? 'npm start' : '';
  if (eds && !server) server = 'aem up';
  if (worker && !server) server = 'npx wrangler dev';
  const kind = eds ? 'eds' : worker ? 'cloudflare-worker' : helixService ? 'helix-service' : pkg.name ? 'node' : 'other';
  return {
    repo: repoSlug(git(dir, ['remote', 'get-url', 'origin'])),
    kind,
    defaultBranch,
    commands: {
      install: has('package-lock.json') ? 'npm ci' : has('pnpm-lock.yaml') ? 'pnpm i' : has('yarn.lock') ? 'yarn' : pkg.name ? 'npm i' : '',
      lint: scripts.lint ? 'npm run lint' : '',
      test: scripts.test && !/no test specified/.test(scripts.test) ? 'npm test' : '',
      build: scripts.build ? 'npm run build' : '',
      server,
    },
    serverNote: eds ? 'if `aem up` crashes watching .git/…/fsmonitor--daemon.ipc in a worktree, run `git fsmonitor--daemon stop && git config core.fsmonitor false` there and retry' : '',
    testFrameworks: testFw,
    usesEsmock,
  };
}

export function renderProfile(facts, branchHint) {
  const c = facts.commands;
  const line = (k, v) => (v ? `- **${k}:** \`${v}\`` : `- **${k}:** _none detected_`);
  const verify = {
    eds: 'lint → start local server → load changed pages/blocks at localhost → check console errors, layout at mobile/desktop, and compare against the reference page; run Lighthouse on changed pages when performance-sensitive.',
    'cloudflare-worker': 'lint → unit tests → `wrangler dev` smoke test of changed routes (incl. CORS preflight for new/changed paths).',
    'helix-service': 'lint → unit tests (follow existing test patterns; no new mocking libs, no timeouts) → check downstream consumers of changed response formats.',
    node: 'lint → tests → run the changed entry point locally.',
    other: 'run whatever validation the repo provides; state clearly what could not be verified.',
  }[facts.kind];
  return `# Profile: ${facts.repo || '(no origin)'}

<!-- Generated by \`dev-harness profile init\`. Edit freely; the "Notes" section is yours. -->

- **Kind:** ${facts.kind}
- **Default branch:** \`${facts.defaultBranch}\` (never commit to it directly)
${branchHint ? `- **Branch names:** ${branchHint}\n` : ''}${line('Install', c.install)}
${line('Lint', c.lint)}
${line('Test', c.test)}
${line('Build', c.build)}
${line('Local server', c.server)}${facts.serverNote ? ` — ${facts.serverNote}` : ''}
- **Test frameworks:** ${facts.testFrameworks.join(', ') || 'none detected'}${facts.usesEsmock ? ' (esmock already used)' : ''}

## Verify recipe
${verify}

## Notes (edit me)
- Related repos / local clone paths:
- Consumers that must keep working (back-compat):
- Gotchas:
`;
}
