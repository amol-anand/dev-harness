#!/usr/bin/env node
// Helpers used by install.sh. Each subcommand is idempotent.
import {
  readFileSync, writeFileSync, existsSync, mkdirSync, readdirSync,
} from 'node:fs';
import { join, dirname, resolve, basename } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadConfig, HARNESS_HOME, expandHome } from '../lib/config.mjs';
import { localPaths } from '../lib/context.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const MARKER = 'DEV_HARNESS_HOOK=1';
const isOurs = (cmd) => cmd.startsWith(MARKER) || cmd.includes(`"${join(ROOT, 'hooks')}/`);
const [cmd, ...args] = process.argv.slice(2);

function renderAgents(outDir, runtime) {
  const cfg = loadConfig();
  mkdirSync(outDir, { recursive: true });
  const written = [];
  for (const f of readdirSync(join(ROOT, 'agents')).filter((x) => x.endsWith('.agent.md'))) {
    let src = readFileSync(join(ROOT, 'agents', f), 'utf8');
    if (runtime === 'claude') {
      src = src.replace(/^model: .*$/m, 'model: opus');
    } else {
      src = src.replace('{{CODE_MODEL}}', cfg.review.codeModel).replace('{{SECURITY_MODEL}}', cfg.review.securityModel);
    }
    src = src.replace(/^---\n/, '---\n# generated by dev-harness install.sh — edit the template in the harness repo\n');
    const name = runtime === 'claude' ? f.replace('.agent.md', '.md') : f;
    writeFileSync(join(outDir, name), src);
    written.push(join(outDir, name));
  }
  console.log(written.join('\n'));
}

function composeInstructions(out) {
  const cfg = loadConfig();
  const parts = [readFileSync(join(ROOT, 'instructions', 'global.md'), 'utf8').trim()];
  const local = localPaths(cfg).instructions;
  if (existsSync(local)) {
    const body = readFileSync(local, 'utf8').replace(/<!--[\s\S]*?-->/g, '').trim();
    if (body && body !== '# Personal instructions') parts.push(body);
  }
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, `<!-- generated by dev-harness install.sh from instructions/global.md + ${local}. Re-run install.sh after editing. -->\n\n${parts.join('\n\n')}\n`);
}

function copilotHooks(out, node) {
  const cmdFor = (script) => `"${node}" "${join(ROOT, 'hooks', script)}"`;
  const json = {
    version: 1,
    hooks: {
      preToolUse: [{ type: 'command', bash: cmdFor('guard.mjs'), timeoutSec: 10 }],
      sessionStart: [{ type: 'command', bash: cmdFor('session-start.mjs'), timeoutSec: 15 }],
    },
  };
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, `${JSON.stringify(json, null, 2)}\n`);
}

function stripOurs(list) {
  return (list || [])
    .map((entry) => ({ ...entry, hooks: (entry.hooks || []).filter((h) => !isOurs(String(h.command || ''))) }))
    .filter((entry) => entry.hooks.length);
}

function claudeHooks(settingsPath, mode, node) {
  const settings = existsSync(settingsPath) ? JSON.parse(readFileSync(settingsPath, 'utf8')) : {};
  settings.hooks ||= {};
  settings.hooks.PreToolUse = stripOurs(settings.hooks.PreToolUse);
  settings.hooks.SessionStart = stripOurs(settings.hooks.SessionStart);
  if (mode === 'add') {
    const c = (s) => `${MARKER} "${node}" "${join(ROOT, 'hooks', s)}"`;
    settings.hooks.PreToolUse.push({ matcher: 'Bash|Edit|Write|MultiEdit|NotebookEdit', hooks: [{ type: 'command', command: c('guard.mjs'), timeout: 10 }] });
    settings.hooks.SessionStart.push({ hooks: [{ type: 'command', command: c('session-start.mjs'), timeout: 15 }] });
  }
  for (const k of ['PreToolUse', 'SessionStart']) if (!settings.hooks[k].length) delete settings.hooks[k];
  if (!Object.keys(settings.hooks).length) delete settings.hooks;
  mkdirSync(dirname(settingsPath), { recursive: true });
  writeFileSync(settingsPath, `${JSON.stringify(settings, null, 2)}\n`);
}

const MODEL_BACKUP = join(HARNESS_HOME, 'backups', 'models.json');

function readJson(p) { return existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : {}; }

/** Set the runtime's default model, remembering the user's original value once. */
function setModel(settingsPath, model) {
  const settings = readJson(settingsPath);
  const backup = readJson(MODEL_BACKUP);
  if (!(settingsPath in backup)) {
    backup[settingsPath] = 'model' in settings ? settings.model : null;
    mkdirSync(dirname(MODEL_BACKUP), { recursive: true });
    writeFileSync(MODEL_BACKUP, `${JSON.stringify(backup, null, 2)}\n`);
  }
  settings.model = model;
  mkdirSync(dirname(settingsPath), { recursive: true });
  writeFileSync(settingsPath, `${JSON.stringify(settings, null, 2)}\n`);
}

function restoreModel(settingsPath) {
  const backup = readJson(MODEL_BACKUP);
  if (!(settingsPath in backup) || !existsSync(settingsPath)) return;
  const settings = readJson(settingsPath);
  if (backup[settingsPath] === null) delete settings.model;
  else settings.model = backup[settingsPath];
  writeFileSync(settingsPath, `${JSON.stringify(settings, null, 2)}\n`);
  delete backup[settingsPath];
  writeFileSync(MODEL_BACKUP, `${JSON.stringify(backup, null, 2)}\n`);
}

switch (cmd) {
  case 'set-model': setModel(args[0], args[1]); break;
  case 'restore-model': restoreModel(args[0]); break;
  case 'dev-model': { const c = loadConfig(); console.log(c.dev.setDefaults ? (args[0] === 'claude' ? c.dev.claudeModel : c.dev.model) : ''); break; }
  case 'render-agents': renderAgents(args[0], args[1]); break;
  case 'compose-instructions': composeInstructions(args[0]); break;
  case 'copilot-hooks': copilotHooks(args[0], args[1]); break;
  case 'extra-skills': { // harness skills keep their names
    const taken = new Set(readdirSync(join(ROOT, 'skills')));
    for (const p of [].concat(loadConfig().skills.extra)) {
      const src = resolve(expandHome(String(p)));
      if (src.includes('\n') || taken.has(basename(src)) || !existsSync(join(src, 'SKILL.md'))) console.error(`  ! skipped extra skill ${p} (name taken or no SKILL.md)`);
      else { taken.add(basename(src)); console.log(src); }
    }
    break;
  }
  case 'claude-hooks': claudeHooks(args[0], args[1], args[2]); break;
  default: console.error(`unknown: ${cmd}`); process.exit(1);
}
